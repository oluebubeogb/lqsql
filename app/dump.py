"""CSV + SQL dump generation (streaming)."""
import csv
import datetime as dt
import decimal
import io
import json
import re

from sqlalchemy import text

from .db import DB, to_text
from .browse import select_list, build_where


def _csv_chunks(header, rows_iter):
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(header)
    n = 0
    for r in rows_iter:
        w.writerow([to_text(v) for v in r])
        n += 1
        if n % 500 == 0:
            yield buf.getvalue()
            buf.seek(0)
            buf.truncate()
    yield buf.getvalue()


def table_csv(db: DB, schema, table, filters=None, sort=None, direction="asc"):
    meta = db.table_meta(schema, table)
    cols = [c for c in meta["columns"]]
    if db.kind == "postgresql":
        sel = ", ".join(f"CAST({db.q(c['name'])} AS text)" for c in cols)
    else:
        sel = ", ".join(db.q(c["name"]) for c in cols)
    where, params = build_where(db, meta, filters)
    order = ""
    if sort and sort in {c["name"] for c in cols}:
        order = f" ORDER BY {db.q(sort)} {'DESC' if direction == 'desc' else 'ASC'}"
    sql = f"SELECT {sel} FROM {db.qt(schema, table)}{where}{order}"

    def gen():
        with db.engine.connect().execution_options(stream_results=True, yield_per=1000) as c:
            res = c.execute(text(sql), params)
            yield from _csv_chunks([c_["name"] for c_ in cols], res)
    return gen()


def query_csv(db: DB, sql: str):
    def gen():
        raw = db.engine.raw_connection()
        try:
            cur = raw.cursor()
            cur.execute(sql)
            if not cur.description:
                yield "rowcount\n" + str(cur.rowcount) + "\n"
                return
            header = [d[0] for d in cur.description]

            def rows():
                while True:
                    batch = cur.fetchmany(1000)
                    if not batch:
                        break
                    yield from batch
            yield from _csv_chunks(header, rows())
            raw.rollback()
        finally:
            raw.close()
    return gen()


# ---------- SQL literals ----------

def literal(db: DB, v) -> str:
    if v is None:
        return "NULL"
    if db.kind == "postgresql":
        # PG path selects everything as text, server casts literal to the column type
        return "'" + str(v).replace("'", "''") + "'"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float, decimal.Decimal)):
        return str(v)
    if isinstance(v, (bytes, bytearray, memoryview)):
        return "X'" + bytes(v).hex() + "'"
    if isinstance(v, (dt.datetime, dt.date, dt.time, dt.timedelta)):
        s = str(v) if isinstance(v, dt.timedelta) else v.isoformat(sep=" ") if isinstance(v, dt.datetime) else v.isoformat()
        return "'" + s + "'"
    if isinstance(v, (dict, list)):
        v = json.dumps(v)
    s = str(v)
    if db.kind == "mysql":
        s = s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r").replace("\x00", "\\0")
        return "'" + s + "'"
    return "'" + s.replace("'", "''") + "'"


# ---------- DDL ----------

def _pg_table_ddl(db: DB, c, schema, table, drop: bool):
    oid = c.execute(text("SELECT c.oid FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=:s AND c.relname=:t"),
                    {"s": schema, "t": table}).scalar()
    qt = db.qt(schema, table)
    pre, body, post, fks, seqs = [], [], [], [], []
    cols = c.execute(text("""
        SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull, pg_get_expr(d.adbin, d.adrelid),
               a.attidentity, a.attgenerated, pg_get_serial_sequence(:qt, a.attname)
        FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
        WHERE a.attrelid=:o AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum"""), {"o": oid, "qt": qt}).all()
    for name, typ, notnull, default, ident, gen, seq in cols:
        line = f"  {db.q(name)} {typ}"
        if ident:
            line += " GENERATED ALWAYS AS IDENTITY" if ident == "a" else " GENERATED BY DEFAULT AS IDENTITY"
        elif gen == "s":
            line += f" GENERATED ALWAYS AS ({default}) STORED"
        elif default is not None:
            line += f" DEFAULT {default}"
            if seq and default.startswith("nextval("):
                pre.append(f"CREATE SEQUENCE IF NOT EXISTS {seq};")
        if notnull:
            line += " NOT NULL"
        body.append(line)
        if seq:
            seqs.append((seq, name))
    cons = c.execute(text("SELECT conname, contype, pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid=:o ORDER BY contype, conname"),
                     {"o": oid}).all()
    for name, typ, defn in cons:
        if typ == "f":
            fks.append(f"ALTER TABLE {qt} ADD CONSTRAINT {db.q(name)} {defn};")
        elif typ in ("p", "u", "c", "x"):
            body.append(f"  CONSTRAINT {db.q(name)} {defn}")
    idx = c.execute(text("""
        SELECT pg_get_indexdef(i.indexrelid) FROM pg_index i
        WHERE i.indrelid=:o AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid=i.indexrelid AND k.conrelid=:o)"""),
                    {"o": oid}).scalars().all()
    post.extend(f"{d};" for d in idx)
    out = []
    if drop:
        out.append(f"DROP TABLE IF EXISTS {qt} CASCADE;")
    out.extend(pre)
    out.append(f"CREATE TABLE {qt} (\n" + ",\n".join(body) + "\n);")
    has_always_ident = any(r[4] == "a" for r in cols)
    gen_cols = {r[0] for r in cols if r[5] == "s"}
    return "\n".join(out), post, fks, seqs, has_always_ident, gen_cols


def sql_dump(db: DB, schema, tables: list[str], ddl=True, data=True, drop=False, batch=200):
    from . import __version__

    def gen():
        now = dt.datetime.now().isoformat(timespec="seconds")
        yield f"-- lqSQL {__version__} dump\n-- engine: {db.kind}  schema: {schema}  generated: {now}\n\n"
        with db.engine.connect() as c:
            metas = {t: db.table_meta(schema, t) for t in tables}
            real = [t for t in tables if not metas[t]["view"]]
            views = [t for t in tables if metas[t]["view"]]
            late = []
            if db.kind == "mysql":
                yield "SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS=0;\n\n"
            elif db.kind == "sqlite":
                yield "PRAGMA foreign_keys=OFF;\nBEGIN TRANSACTION;\n\n"
            else:
                # schema-qualify every expression/definition we read (transaction-local)
                c.execute(text("SELECT set_config('search_path', '', true)"))
                yield "SET client_encoding = 'UTF8';\nSET standard_conforming_strings = on;\n"
                if ddl:
                    exts = c.execute(text("SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY extname")).scalars().all()
                    for e in exts:
                        yield f"CREATE EXTENSION IF NOT EXISTS {db.q(e)};\n"
                    if schema != "public":
                        yield f"CREATE SCHEMA IF NOT EXISTS {db.q(schema)};\n"
                yield "\n"
            for t in real:
                meta = metas[t]
                qt = db.qt(schema, t)
                # PG dumps stay schema-qualified; MySQL/SQLite dumps target whichever DB they are imported into
                ot = qt if db.kind == "postgresql" else db.q(t)
                yield f"-- ---------------------------------------------\n-- Table {t}\n-- ---------------------------------------------\n"
                post, fks, seqs, always, gen_cols = [], [], [], False, set()
                if ddl:
                    if db.kind == "postgresql":
                        stmt, post, fks, seqs, always, gen_cols = _pg_table_ddl(db, c, schema, t, drop)
                        late.extend(fks)
                        yield stmt + "\n"
                    elif db.kind == "mysql":
                        row = c.execute(text(f"SHOW CREATE TABLE {qt}")).first()
                        if drop:
                            yield f"DROP TABLE IF EXISTS {ot};\n"
                        yield row[1] + ";\n"
                        for tr in c.execute(text("SELECT TRIGGER_NAME FROM information_schema.TRIGGERS WHERE EVENT_OBJECT_SCHEMA=:s AND EVENT_OBJECT_TABLE=:t"), {"s": schema, "t": t}).scalars().all():
                            body = c.execute(text(f"SHOW CREATE TRIGGER {db.qt(schema, tr)}")).first()[2]
                            post.append(re.sub(r"DEFINER=\S+\s+", "", body) + ";")
                    else:
                        sch = db.q(schema)
                        sql = c.execute(text(f"SELECT sql FROM {sch}.sqlite_master WHERE type='table' AND name=:t"), {"t": t}).scalar()
                        if drop:
                            yield f"DROP TABLE IF EXISTS {ot};\n"
                        yield (sql or "") + ";\n"
                        post = [r + ";" for r in c.execute(text(f"SELECT sql FROM {sch}.sqlite_master WHERE type IN ('index','trigger') AND tbl_name=:t AND sql IS NOT NULL"), {"t": t}).scalars().all()]
                elif db.kind == "postgresql":
                    _, _, _, seqs, always, gen_cols = _pg_table_ddl(db, c, schema, t, False)
                elif db.kind == "mysql":
                    gen_cols = {x["name"] for x in meta["columns"] if x["generated"]}
                else:
                    gen_cols = {x["name"] for x in meta["columns"] if x["generated"]}
                if data:
                    cols = [x["name"] for x in meta["columns"] if x["name"] not in gen_cols]
                    if cols:
                        if db.kind == "postgresql":
                            sel = ", ".join(f"CAST({db.q(n)} AS text)" for n in cols)
                        else:
                            sel = ", ".join(db.q(n) for n in cols)
                        head = f"INSERT INTO {ot} ({', '.join(db.q(n) for n in cols)})"
                        if always:
                            head += " OVERRIDING SYSTEM VALUE"
                        head += " VALUES\n"
                        sc = db.engine.connect().execution_options(stream_results=True, yield_per=1000)
                        try:
                            res = sc.execute(text(f"SELECT {sel} FROM {qt}"))
                            chunk = []
                            for r in res:
                                chunk.append("(" + ", ".join(literal(db, v) for v in r) + ")")
                                if len(chunk) >= batch:
                                    yield head + ",\n".join(chunk) + ";\n"
                                    chunk = []
                            if chunk:
                                yield head + ",\n".join(chunk) + ";\n"
                        finally:
                            sc.close()
                for p in post:
                    yield p + "\n"
                for seq, col in seqs:
                    yield f"SELECT setval('{seq}', COALESCE((SELECT MAX({db.q(col)}) FROM {qt}), 1), (SELECT MAX({db.q(col)}) FROM {qt}) IS NOT NULL);\n"
                yield "\n"
            if ddl:
                for v in views:
                    qt = db.qt(schema, v)
                    ot = qt if db.kind == "postgresql" else db.q(v)
                    if db.kind == "postgresql":
                        mat = c.execute(text("SELECT c.relkind FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=:s AND c.relname=:t"), {"s": schema, "t": v}).scalar()
                        d = c.execute(text("SELECT pg_get_viewdef(CAST(:q AS regclass), true)"), {"q": qt}).scalar()
                        kind = "MATERIALIZED VIEW" if mat == "m" else "VIEW"
                        if drop:
                            yield f"DROP {kind} IF EXISTS {qt} CASCADE;\n"
                        yield f"CREATE {kind} {qt} AS\n{d.rstrip().rstrip(';')};\n\n"
                    elif db.kind == "mysql":
                        row = c.execute(text(f"SHOW CREATE VIEW {qt}")).first()
                        if drop:
                            yield f"DROP VIEW IF EXISTS {ot};\n"
                        yield re.sub(r"DEFINER=\S+\s+", "", row[1]) + ";\n\n"
                    else:
                        sql = c.execute(text(f"SELECT sql FROM {db.q(schema)}.sqlite_master WHERE type='view' AND name=:t"), {"t": v}).scalar()
                        if drop:
                            yield f"DROP VIEW IF EXISTS {ot};\n"
                        yield (sql or "") + ";\n\n"
                for fk in late:
                    yield fk + "\n"
            if db.kind == "mysql":
                yield "\nSET FOREIGN_KEY_CHECKS=1;\n"
            elif db.kind == "sqlite":
                yield "\nCOMMIT;\n"
        yield "-- end of dump\n"
    return gen()
